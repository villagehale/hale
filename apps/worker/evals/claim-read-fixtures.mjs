/** The instant fields each source carries, from its family-local wall time. */
function rowFor({ local, ...row }, timeZone) {
  if (row.source === 'calendar' || row.source === 'booking') {
    return { ...row, startsAt: at(local, timeZone) };
  }
  if (row.source === 'cancelled') return { ...row, startsAt: local ? at(local, timeZone) : null };
  if (row.source === 'send_receipt') return { ...row, sentAt: at(local, timeZone) };
  if (row.source === 'live_sequence') return { ...row, opensAt: at(local, timeZone) };
  if (row.source === 'mintable_window') return { ...row, opensForFamilyAt: at(local, timeZone) };
  return row;
}

/** The zone is a pure function of the id, so adding a fixture never moves another's key. */
const zoneFor = (id) =>
  ZONES[[...id].reduce((sum, ch) => sum + ch.charCodeAt(0), 0) % ZONES.length];

/**
 * claims: [kind, row, sentence?]; refused: [reason, sentence?]. A missing
 * sentence is the whole body (a one-sentence message).
 */
function fx({
  id,
  language,
  category,
  body,
  rows = [],
  claims = [],
  refused = [],
  minted = [],
  inbound,
  residual,
  lane = 'coach',
}) {
  const timeZone = zoneFor(id);
  return {
    id,
    // Every fixture here is written by hand. A real shadow sample is 'shadow_sample', and
    // its text is never printed (lib/claim-read-score.mjs failLines).
    provenance: 'invented',
    language,
    lane,
    category,
    timeZone,
    now: at(NOW, timeZone),
    ...(inbound ? { inbound } : {}),
    body,
    candidates: rows.map((row) => rowFor(row, timeZone)),
    expect: {
      claims: claims.map(([kind, row, sentence = body]) => ({ sentence, kind, row })),
      refused: refused.map(([reason, sentence = body]) => ({ sentence, reason })),
      minted,
    },
    ...(residual ? { residual } : {}),
  };
}

